//! Build script of the worker:
//!
//! - writes `$OUT_DIR/pins.rs` with the SHA-256 digests the worker checks before it uses a file
//!   (spec §6.1, §6.9): the model files from `model.lock.json` and the ONNX Runtime library of
//!   the build target from `ort.lock.json`. A target without a pinned library gets `None`, so the
//!   worker builds and runs without semantic search;
//! - marks the build `gdb_missing` when the dump test of feature `test-probes` cannot run
//!   (`tests/zalloc_dump.rs` is then ignored instead of failing), and `strace_missing` when the
//!   system call test cannot (`tests/strace.rs`). In CI (`CI=true`) on Linux with `test-probes`
//!   a missing tool fails the build instead: the two tests are the evidence of spec criterion 5
//!   and must not be skipped silently there.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use serde_json::Value;

/// Model files whose digests the worker checks, with the constant names in `pins.rs`.
const MODEL_FILES: &[(&str, &str)] = &[
    ("manifest.json", "MANIFEST_SHA256"),
    ("model.onnx", "MODEL_ONNX_SHA256"),
    ("tokenizer.kit", "TOKENIZER_KIT_SHA256"),
];

fn main() {
    write_pins();
    println!("cargo::rerun-if-env-changed=PATH");
    println!("cargo::rerun-if-env-changed=CI");
    if env::var_os("CARGO_FEATURE_TEST_PROBES").is_some() {
        mark_missing("gdb", "gdb_missing");
    } else {
        println!("cargo::rustc-check-cfg=cfg(gdb_missing)");
    }
    mark_missing("strace", "strace_missing");
}

fn write_pins() {
    let root =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets the manifest dir"))
            .join("../..");
    let model_lock = root.join("model.lock.json");
    let ort_lock = root.join("ort.lock.json");
    println!("cargo::rerun-if-changed={}", model_lock.display());
    println!("cargo::rerun-if-changed={}", ort_lock.display());

    let model = read_json(&model_lock);
    let ort = read_json(&ort_lock);
    let mut out =
        String::from("// Generated by build.rs from model.lock.json and ort.lock.json.\n");
    for (file, name) in MODEL_FILES {
        let digest = model["files"][*file]
            .as_str()
            .unwrap_or_else(|| panic!("model.lock.json has no digest of {file}"));
        writeln!(
            out,
            "pub(crate) const {name}: [u8; 32] = {};",
            bytes(digest)
        )
        .expect("String write");
    }

    let target = ort_target();
    let lib = target.and_then(|t| ort["targets"][t]["lib_sha256"].as_str());
    let pinned = lib.map_or_else(
        || "None".to_owned(),
        |digest| format!("Some({})", bytes(digest)),
    );
    writeln!(
        out,
        "pub(crate) const ORT_LIB_SHA256: Option<[u8; 32]> = {pinned};"
    )
    .expect("String write");

    let path = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR")).join("pins.rs");
    fs::write(&path, out).unwrap_or_else(|err| panic!("writing {}: {err}", path.display()));
}

/// Key of the build target in `ort.lock.json`, if it is one of the pinned ones.
fn ort_target() -> Option<&'static str> {
    let os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    match (os.as_str(), arch.as_str()) {
        ("linux", "x86_64") => Some("linux-amd64"),
        ("windows", "x86_64") => Some("windows-amd64"),
        ("macos", "aarch64") => Some("darwin-arm64"),
        _ => None,
    }
}

fn read_json(path: &Path) -> Value {
    let text =
        fs::read_to_string(path).unwrap_or_else(|err| panic!("reading {}: {err}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|err| panic!("parsing {}: {err}", path.display()))
}

/// The Rust array literal of a 64-digit lower-case hex digest.
fn bytes(hex: &str) -> String {
    assert!(
        hex.len() == 64 && hex.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')),
        "{hex:?} is not a SHA-256 hex digest"
    );
    let items: Vec<String> = (0..32)
        .map(|i| format!("0x{}", &hex[2 * i..2 * i + 2]))
        .collect();
    format!("[{}]", items.join(", "))
}

/// Declares `cfg(<name>)` and sets it when `tool --version` does not run; panics instead when
/// the tests that need the tool must run (see [`tool_required`]).
fn mark_missing(tool: &str, name: &str) {
    println!("cargo::rustc-check-cfg=cfg({name})");
    let status = Command::new(tool)
        .arg("--version")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    if !status.is_ok_and(|s| s.success()) {
        assert!(
            !tool_required(),
            "{tool} not found: CI runs its test with feature test-probes on Linux; install {tool}"
        );
        println!("cargo::rustc-cfg={name}");
    }
}

/// Whether the tests of the probes must run: in CI (`CI=true`, as GitHub Actions sets it), on a
/// Linux target, with feature `test-probes`. The package builds have no `test-probes`.
fn tool_required() -> bool {
    env::var("CI").is_ok_and(|v| v == "true")
        && env::var("CARGO_CFG_TARGET_OS").is_ok_and(|os| os == "linux")
        && env::var_os("CARGO_FEATURE_TEST_PROBES").is_some()
}
